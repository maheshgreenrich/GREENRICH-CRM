'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const crm=fs.readFileSync('greenrich-crm-inline.js','utf8');
const settings=fs.readFileSync('greenrich-company-admin.js','utf8');
const tags=fs.readFileSync('greenrich-customer-tags.js','utf8');
const html=fs.readFileSync('secure.html','utf8');
const css=fs.readFileSync('greenrich-crm-inline.css','utf8');
const app=fs.readFileSync('greenrich-one.js','utf8');
for(const [name,src] of [['crm',crm],['tags',tags],['settings',settings],['app',app]])new vm.Script(src,{filename:name});
for(const field of ['date','internal_order_id','company_id','channel_id','product_id','qty','shipping_charge','notes'])assert.ok(crm.includes("'"+field+"'"),'Missing sales field '+field);
for(const phrase of ['Platform order ID (optional)','Internal Sales Order ID (automatic)','Company','New Customer','Select Existing','Search existing customer by name, mobile number or email','Duplicate customer: email or mobile number','Insufficient stock for','Second mobile number','tag_ids','Available stock:','data-stock-update','autoProductPricing','round(calc.total+row.shipping_charge)','nextOrderId(copy,targetId)'])assert.ok(crm.includes(phrase),'Sales function missing: '+phrase);
assert.ok(crm.includes('row.tax_rate=Number(product.tax)'),'Product tax must be automatic');
assert.ok(crm.includes('product.stock-=row.qty'),'Stock must decrease after sale');
assert.ok(crm.includes('saveCompanyData(targetId,copy)'),'Sale must save to selected company');
assert.ok(crm.includes('if(consumesStock(row))'),'Only active sales consume stock');
assert.ok(crm.includes('cleanPhone'),'Normalize phone numbers for duplicate detection');
assert.ok(crm.includes('if(!saveCompanyData(targetId,copy))return'),'Save failures must abort.');
assert.ok(settings.includes("['tags','Customer Tags']"),'Customer Tags must be in Settings');
assert.ok(settings.includes('ctx.openTags(host,selected(ctx.user.id))'));
assert.ok(tags.includes('data-tag-edit')&&tags.includes('data-tag-delete'));
assert.ok(tags.includes('db.customers.forEach'),'Deleting tags must remove customer tag assignments');
assert.ok(html.includes('greenrich-customer-tags.js'));
for(const header of ['Stock','Tags','Internal / Platform Order ID'])assert.ok(html.includes('>'+header+'</th>'));
assert.ok(css.includes('gr-customer-picker'));
assert.ok(app.includes('GreenRichCustomerTags.mount'));
console.log('PASS: sales company, IDs, customer search & duplicates, product tax, stock, shipping, tags and admin Settings');
