'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const crm=fs.readFileSync('greenrich-crm-inline.js','utf8');
const leads=fs.readFileSync('greenrich-lead-pipeline.js','utf8');
const alarm=fs.readFileSync('greenrich-followup-alarm.js','utf8');
assert.ok(!alarm.includes('open(due.data[0])'),'Due reminders must not open a blocking modal');
assert.ok(alarm.includes('alreadyNotified.add(key)'),'No repeating reminder toast for the same due time');
new vm.Script(crm);new vm.Script(leads);
// Run the exact shipping production stock transition function, not a duplicate copy.
const begin=crm.indexOf('const consumesStock=s=>');
const end=crm.indexOf('function validateCustomer(',begin);
assert.ok(begin>=0&&end>begin);
const logic=vm.runInNewContext(crm.slice(begin,end)+';({consumesStock,adjustStockForSale})');
const product=()=>({id:'bin',name:'Composter Bin',stock:10});
const store={products:[product()]},old=(qty,status='Pending',id='bin')=>({qty,status,product_id:id});
logic.adjustStockForSale(store,null,old(2));assert.equal(store.products[0].stock,8,'Order 2 from 10 = 8');
logic.adjustStockForSale(store,old(2),old(2,'Cancelled'));assert.equal(store.products[0].stock,10,'Cancel releases 2');
logic.adjustStockForSale(store,old(2,'Cancelled'),null);assert.equal(store.products[0].stock,10,'Delete cancelled order cannot double-add');
logic.adjustStockForSale(store,old(2,'Cancelled'),old(2));assert.equal(store.products[0].stock,8,'Reactivation reserves again');
logic.adjustStockForSale(store,old(2),old(4));assert.equal(store.products[0].stock,6,'Editing 2 → 4 reduces stock by 2 more');
logic.adjustStockForSale(store,old(4),old(4,'Returned'));assert.equal(store.products[0].stock,10,'Return restores reserved stock');
logic.adjustStockForSale(store,old(4,'Returned'),old(4,'Returned'));assert.equal(store.products[0].stock,10,'Repeated cancellation/return does not add twice');
logic.adjustStockForSale(store,old(4,'Returned'),null);assert.equal(store.products[0].stock,10,'Delete returned order no stock effect');
assert.throws(()=>logic.adjustStockForSale(store,null,old(11)),/Insufficient stock/);assert.equal(store.products[0].stock,10,'Rejected SO does not change balance');
logic.adjustStockForSale(store,null,old(3));assert.equal(store.products[0].stock,7);
store.products.push({id:'other',name:'Another Bin',stock:5});
logic.adjustStockForSale(store,old(3),old(2,'Pending','other'));
assert.equal(store.products[0].stock,10,'Changing SKU releases old stock');
assert.equal(store.products[1].stock,3,'Changing SKU reserves new stock');
assert.ok(crm.includes("status:k==='tasks'?'Open':k==='sales'?'Pending':'Completed'"),'New SO defaults Pending');
assert.ok(crm.includes('adjustStockForSale(copy,item,null)'), 'SO deletion uses shared stock accounting');
assert.ok(crm.includes("new_address2:lead.address2"),'Lead address2 prefilled');
assert.ok(crm.includes("new_notes:lead.notes"),'Lead conversation/notes carried to SO customer');
assert.ok(crm.includes("gr_pipeline_link_customer"),'Link new customer to lead even on pending SO');
assert.ok(crm.includes("current.data.stage==='Won'"),'Do not modify Won leads on repeat purchase');
assert.ok(crm.includes('const existingCustomer=shared?.customers?.find'),'Duplicate customer race is reconciled');
assert.ok(leads.includes("const pulseTick=setInterval("),'Board refreshes due state while open');
assert.ok(leads.includes('updateDueCards(ctx)'),'Highlight updated on board render');
assert.ok(leads.includes('prefers-reduced-motion:reduce'),'Respect reduced-motion preference');
const dueStart=leads.indexOf(' function updateDueCards(ctx){'),dueEnd=leads.indexOf(' function draw(ctx)',dueStart);
assert.ok(dueStart>=0&&dueEnd>dueStart);
const now=Date.now();
const card=at=>({dataset:{followupAt:String(at)},classList:{classes:new Set(),toggle(name,on){on?this.classes.add(name):this.classes.delete(name)}},message:{hidden:true},querySelector(){return this.message}});
const due=card(now-1000),future=card(now+3600000),empty=card(0);
const scope={root:{isConnected:true,querySelectorAll(){return [due,future,empty]}}};
vm.runInNewContext(leads.slice(dueStart,dueEnd)+';updateDueCards(ctx)',{ctx:scope,Date});
assert.ok(due.classList.classes.has('gl-followup-due')&&!due.message.hidden,'Only overdue lead pulses');
assert.ok(!future.classList.classes.has('gl-followup-due')&&future.message.hidden,'Future lead stays normal');
assert.ok(!empty.classList.classes.has('gl-followup-due')&&empty.message.hidden,'Unscheduled lead stays normal');
console.log('PASS: Stock 10→8→10; cancellation/return/delete idempotent; alternate products; lead customer conversion; exact-time lead-only pulse.');
