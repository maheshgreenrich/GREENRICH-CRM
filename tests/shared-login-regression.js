'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const read=file=>fs.readFileSync(file,'utf8');
const root=read('index.html'),secure=read('secure.html');
const config=read('greenrich-public-config.js'),app=read('greenrich-one.js');
assert.match(root,/secure\.html/,'Root must open secure employee login');
assert.doesNotMatch(root,/demoUsername|demoPassword|Login to local demo|demo\.js/,'Root must not offer a browser-only account');
assert.match(secure,/<input id="email" type="email"/,'Login must accept employee email');
assert.match(secure,/<input id="password" type="password"/,'Password must use an actual password input');
assert.ok(secure.indexOf('greenrich-public-config.js')<secure.indexOf('greenrich-one.js'),'Public config must load before secure app');
assert.match(config,/uawgwkplkvahhmhvroul\.supabase\.co/,'Same GreenRich Supabase project on every device');
assert.match(config,/sb_publishable_/,'Frontend must only use a public API key');
assert.doesNotMatch(config,/sb_secret_|service_role\\s*[:=]/,'Never publish Supabase secret API keys');
assert.match(app,/window\.GREENRICH_PUBLIC_CONFIG/,'App bootstrap must use public company configuration');
assert.match(app,/localStorage\.setItem\('gr-supabase-url',publicConfig\.supabaseUrl\)/);
assert.match(app,/localStorage\.setItem\('gr-supabase-key',publicConfig\.publishableKey\)/);
assert.match(app,/auth\.signInWithPassword/,'Authentication must be checked on Supabase server');
assert.doesNotMatch(root,/greenrich-demo-2026/,'Local-only demo database must not be used as a production login');
new vm.Script(config);
new vm.Script(app);
console.log('PASS: Shared Supabase Auth is the public default; new devices connect automatically with a publishable-only key');
