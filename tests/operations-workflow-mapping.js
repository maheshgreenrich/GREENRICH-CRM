'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const read=f=>fs.readFileSync(f,'utf8');
const app=read('greenrich-one.js'),html=read('secure.html'),ops=read('greenrich-operations.js'),
 seed=read('greenrich-operations-seed.js'),css=read('greenrich-operations.css'),
 sql=read('supabase/migrations/20261030110000_ops_workflow_records.sql');
for(const [name,code] of [['app',app],['operations',ops],['workbook draft seed',seed]])new vm.Script(code,{filename:name});
const sandbox={window:{}};
vm.runInNewContext(seed,sandbox);
const v=sandbox.window.GreenRichOperationsSeed;
assert.equal(v.materials.length,31);
assert.equal(v.materials.filter(x=>x.type==='FG').length,1);
assert.equal(v.materials.filter(x=>x.type==='SFG').length,7);
assert.equal(v.materials.filter(x=>x.type==='IM').length,5);
assert.equal(v.materials.filter(x=>x.type==='RM').length,18);
assert.equal(v.vendors.length,8);
assert.equal(v.bom.length,30);
assert.equal(v.records.length,69);
assert.equal(new Set(v.records.map(x=>x.kind+'|'+x.record_id)).size,69);
assert.ok(v.materials.every(x=>x.status==='Draft'&&x.needs_review));
assert.ok(v.bom.every(x=>x.status==='Draft'&&x.needs_review));
assert.equal([...v.materials.filter(x=>x.qty===null).map(x=>x.code)].sort().join(','),'RM-002,RM-003,RM-004,RM-009');
assert.ok(v.materials.some(x=>x.code==='FG-001'&&x.name.includes('2000 LTR')));
assert.ok(v.materials.some(x=>x.code==='IM-004'&&x.preferred_vendor==='SM Engineering'));
assert.ok(v.vendors.some(x=>x.name==='Balaji Fastners'));
assert.ok(v.materials.some(x=>x.code==='RM-001'&&x.qty===50&&x.uom==='kg'),'Source quantity must not be silently altered');
assert.ok(ops.includes("kind==='bom'")&&ops.includes("payload.status==='Validated'"),'BOM verification and Admin gate missing');
assert.ok(ops.includes('No purchase or work-order demand is automatically released'),'Unapproved material plan cannot drive purchasing');
assert.ok(ops.includes("values.status")===false,'Operations must not alter existing Sales/Dispatch state');
assert.ok(ops.includes("db.from('gr_ops_records')")&&ops.includes("ignoreDuplicates:true"));
assert.ok(ops.includes('accepted_qty')&&ops.includes('rejected_qty'),'Incoming material and QC checks need accepted/rejected quantities');
assert.ok(ops.includes('quality_cleared')&&ops.includes('commercial_cleared')&&ops.includes('packing_slip'),'Dispatch checklist must include quality and Accounts');
assert.ok(app.includes('operations:')&&app.includes("page==='operations'"),'Operations must be directly accessible from sidebar');
assert.ok(html.includes('greenrich-operations-seed.js?v=20261030-ops-1'));
assert.ok(html.includes('greenrich-operations.js?v='),'Operations module must be loaded with a versioned asset');
assert.ok(html.includes('greenrich-operations.css?v=20261030-ops-1'));
assert.ok(html.includes('greenrich-workflow-training.js?v=20261030-training-1'),'Training module must load before Operations');
assert.ok(css.includes('.gr-ops-flow')&&css.includes('.gr-ops-dialog'),'Operations workspace mobile layout');
assert.ok(sql.includes('enable row level security')&&sql.includes('gr_ops_allowed')&&sql.includes('company=any(p.company_ids)'));
assert.ok(!sql.includes('alter table public.gr_attendance')&&!sql.includes('update public.gr_crm_records'));
console.log('PASS Operations Phase 1: 31 materials, eight source vendors, draft BOM hierarchy, company/role RLS, procurement/production/QC workflows and unchanged Attendance');
