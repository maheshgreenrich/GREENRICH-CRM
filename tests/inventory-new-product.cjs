'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const script=fs.readFileSync('greenrich-inventory.js','utf8');
const html=fs.readFileSync('secure.html','utf8');
const win={};vm.runInNewContext(script,{window:win},{filename:'greenrich-inventory.js'});
assert.equal(typeof win.GreenRichInventory.mount,'function');
const make=win.GreenRichInventory.prepareInventoryRecord;
assert.equal(typeof make,'function');
const base={company_id:'grow-india',name:'New 25L Composter',code:' grtest25 ',stage:'FG',uom:'nos',source_type:'Make',
 saleable:true,purchasable:false,price:'3200',tax:'12',reference:'GR-25'};
const fg=make(base,[],'id-1');
assert.equal(fg.kind,'products');
assert.equal(fg.payload.sku,'GRTEST25');
assert.equal(fg.payload.stock,0);
assert.equal(fg.payload.price,3200);
assert.equal(fg.payload.saleable,true);
assert.equal(fg.payload.purchasable,false);
assert.equal(fg.payload.reference,'GR-25');
const raw=make({...base,name:'Plain SS sheet',code:'RM-99',stage:'RM',uom:'kg',saleable:false,purchasable:true,source_type:'Buy'},[],'id-2');
assert.equal(raw.kind,'material');
assert.equal(raw.payload.type,'RM');
assert.equal(raw.payload.qty,null);
assert.equal(raw.payload.purchasable,true);
const subcontract=make({...base,code:'IM-99',stage:'IM',saleable:false,purchasable:false,source_type:'Subcontract'},[],'id-3');
assert.equal(subcontract.payload.has_job_work,true);
assert.throws(()=>make({...base,code:'GRCOM25'},[{code:'GRCOM25',company_id:'grow-india'}],'id-4'),/already exists/);
assert.throws(()=>make({...base,code:'bad code'},[],'id-4'),/valid product code/);
assert.throws(()=>make({...base,price:'-1'},[],'id-4'),/Sales Price/);
assert.match(html,/greenrich-inventory\.js\?v=20261121-new-inventory-page-v10/);
assert.ok(script.includes('data-inv-create-open'));
assert.ok(script.includes('data-inv-create-form'));
assert.ok(script.includes('createInventory(event)'));
console.log('PASS: Add New Inventory supports FG, RM and job work items; validates SKU and never posts opening stock.');
