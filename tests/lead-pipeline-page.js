'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const html=fs.readFileSync('secure.html','utf8');
const core=fs.readFileSync('greenrich-one.js','utf8');
const crm=fs.readFileSync('greenrich-crm-inline.js','utf8');
const pipeline=fs.readFileSync('greenrich-lead-pipeline.js','utf8');
for(const [name,code] of [['core',core],['CRM',crm],['pipeline',pipeline]])new vm.Script(code,{filename:name});
const tmpl=html.match(/<template id="grCrmTemplate">([\s\S]*?)<\/template>/)?.[1]||'';
assert.ok(tmpl.includes('<section id="leads" class="page"><div id="gr-lead-pipeline-root"'), 'Leads page must embed pipeline in CRM template');
assert.ok(!tmpl.includes('id="leads-table"'),'The retired Leads table must not be rendered');
assert.ok(!tmpl.includes('id="leads-search"'),'Legacy filters must not replace Kanban filters');
assert.match(html,/greenrich-lead-pipeline\.js\?v=/,'Pipeline JS must load on secure.html');
assert.match(html,/greenrich-crm-inline\.js\?v=/,'CRM JS must load on secure.html');
assert.ok(html.indexOf('greenrich-lead-pipeline.js?v=')<html.indexOf('greenrich-crm-inline.js?v='),'Pipeline should load before CRM');
assert.match(crm,/GreenRichLeadPipeline\.mount\(\$\('#gr-lead-pipeline-root'\)/,'CRM must mount in Leads root');
assert.ok(!crm.includes("$('#leads-table').innerHTML"),'CRM cannot write the retired table');
assert.ok(crm.includes("p==='leads'"),'New lead action should be managed by pipeline');
assert.ok(pipeline.includes("['New','Contacted','Qualified','Quotation','Won','Lost']"),'Required six lead stages');
assert.ok(pipeline.includes('ondrop=')&&pipeline.includes('p_note'),'Drag/drop must save a required note');
const menu=core.match(/const modules=\[([^\]]+)\]/)?.[1]||'';
assert.ok(menu.includes("'orders'")&&!menu.includes("'sales'"),'Sales Orders must be the only sales sidebar item');
console.log('PASS integrated Leads: Kanban root, current scripts, drag/drop and no duplicate Sales sidebar');
