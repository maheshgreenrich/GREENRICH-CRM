'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const read=f=>fs.readFileSync(f,'utf8');
const directory=read('greenrich-shared-customers.js'),crm=read('greenrich-crm-inline.js'),tags=read('greenrich-customer-tags.js');
const app=read('greenrich-one.js'),settings=read('greenrich-company-admin.js'),html=read('secure.html');
for(const [name,source] of [['shared directory',directory],['CRM',crm],['tags',tags],['app',app],['settings',settings]])new vm.Script(source,{filename:name});
assert.ok(html.includes('greenrich-shared-customers.js'));
assert.ok(html.indexOf('greenrich-shared-customers.js')<html.indexOf('greenrich-crm-inline.js'),'Shared contacts must load before CRM');
assert.ok(directory.includes("db.from('gr_crm_customers')"));
assert.ok(directory.includes("db.from('gr_crm_tags')"));
assert.ok(directory.includes("['greenrich-crm-v2','greenrich-crm-v2::enviro-solutions']"),'Migration must check both company browser stores');
assert.ok(directory.includes('customer_id=target'),'Existing sales must be remapped to global IDs');
assert.ok(directory.includes('await importLegacy()'),'Existing browser contacts and tags must be imported');
assert.ok(directory.includes('tag_ids:oldTags'),'Customer tags must migrate with contacts');
assert.ok(crm.includes('attachSharedCustomers(data)'),'CRM should use cloud customers and tags');
assert.ok(crm.includes('store.tags=shared.tags'),'Tags must use one shared list for both companies');
assert.ok(crm.includes("inputs.getAll('new_tag_ids')"),'New sale must show and save chosen tags');
assert.ok(crm.includes("id:'gr-new-customer-tags'")||crm.includes('id="gr-new-customer-tags"'),'New customer form should have tag selection');
assert.ok(crm.includes("tagChecks(editorData(),'new_tag_ids',[])"),'New customer tags should be rendered from shared directory');
assert.ok(crm.includes('GreenRichSharedCustomers.saveCustomer(fresh)'),'New Sale must create customer centrally');
assert.ok(crm.includes('await window.GreenRichSharedCustomers.ready({client,admin:isAdmin===true})'));
assert.ok(crm.includes("window.GreenRichSharedCustomers.deleteCustomer(id)"));
assert.ok(app.includes("customers:true"),'All active users should be able to view customers');
assert.ok(app.includes("(m==='customers'&&crmAccess().customers)"),'Customers page should be visible to active users');
assert.ok(app.includes('adminTools===true,db,roleName()===\'Admin\''),'CRM must receive the authenticated database client');
assert.ok(tags.includes('await shared.createTag(name)'),'Tags should be created centrally');
assert.ok(tags.includes('await shared.renameTag(tag.id,name)'),'Tags should be editable centrally');
assert.ok(tags.includes('await shared.deleteTag(tag.id)'),'Tags should be deletable centrally');
assert.doesNotMatch(tags,/localStorage\./,'Tag management must not keep tags in company-specific browser storage');
assert.ok(settings.includes("['tags','Customer Tags']"));
console.log('PASS: shared customers and tags, admin tag CRUD, legacy migration, both companies and new sale picker');
