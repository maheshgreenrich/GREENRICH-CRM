'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const app=read('greenrich-one.js');
const attendance=read('greenrich-attendance-inline.js');
const html=read('attendance-v3.html');
const shell=read('secure.html');
const baseCSS=read('greenrich-one.css');
const attendanceCSS=read('attendance-v3.css');
new vm.Script(app,{filename:'greenrich-one.js'});
new vm.Script(attendance,{filename:'greenrich-attendance-inline.js'});
assert.match(app,/role="switch"/,'A single accessible attendance switch should replace two buttons');
assert.match(app,/aria-checked/);
assert.match(app,/canCheckIn\?'Check In'/);
assert.match(app,/canCheckOut\?'Check Out'/);
assert.doesNotMatch(app,/grHeaderIn|grHeaderOut/,'Legacy double clock button should be removed');
assert.match(app,/menuIcons=\{/,'Nav icons should be defined consistently');
assert.match(app,/gr-menu-icon/);
assert.doesNotMatch(app,/\|\|'◇'/,'Placeholder symbol icons should not be rendered');
assert.match(app,/const \[roleRows,profileResult,permissionRows,employeeRows,settingsRows\]=await Promise\.all/);
assert.match(app,/void attendanceQuick\(\)\.catch/,'Attendance status must not block page rendering');
const executive=read('greenrich-dashboard.js');
assert.match(executive,/gr_attendance/,'Dashboard should read existing attendance figures without modifying attendance');
assert.match(app,/crmCache\.host/,'CRM page switching must reuse the existing mounted workspace');
assert.match(app,/window\.GreenRichCRM\.switchPage/,'Sidebar navigation should change visible CRM pages immediately');
assert.match(attendance,/linkedWorkspace\.client/,'Attendance must reuse verified client');
assert.match(attendance,/void safe\(loadRequests\);await loadMine\(\)/,'Requests should load concurrently with calendar');
assert.match(baseCSS,/#grAttendanceSwitch/,'Switch visual styles must be present');
assert.match(baseCSS,/\.gr-menu-icon/);
assert.match(attendanceCSS,/font-weight:600/,'Attendance headings should use restrained font weights');
for(const [name,value] of [['main attendance',attendance],['standalone attendance',html],['workspace HTML',shell],['main JS',app]])
 assert.doesNotMatch(value,/[\u0B80-\u0BFF]/,name+' must not contain Tamil words');
console.log('PASS single attendance switch, professional icons, lighter typography, parallel loading and English-only content');
