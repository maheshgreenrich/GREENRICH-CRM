'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const read=x=>fs.readFileSync(x,'utf8');
const marketing=read('greenrich-whatsapp-marketing.js');
const css=read('greenrich-whatsapp-marketing.css');
const shell=read('greenrich-one.js');
const html=read('secure.html');
const sql=read('supabase/migrations/20261031090000_dual_whatsapp_marketing.sql');
new vm.Script(marketing,{filename:'greenrich-whatsapp-marketing.js'});
new vm.Script(shell,{filename:'greenrich-one.js'});
for(const x of ['gr_wa_connections','gr_wa_campaigns','gr_wa_contacts','gr_wa_templates','gr_wa_automations','gr_wa_messages'])
 assert.ok(marketing.includes(x)&&sql.includes('public.'+x),'Missing table '+x);
assert.ok(html.includes('greenrich-whatsapp-marketing.js?v='),'Marketing JavaScript not loaded');
assert.ok(html.includes('greenrich-whatsapp-marketing.css?v='),'Marketing CSS not loaded');
assert.ok(html.indexOf('greenrich-whatsapp-marketing.js?v=')<html.indexOf('greenrich-one.js?v='),'Marketing must load before app');
assert.ok(shell.includes("'stock','marketing','operations'"),'Missing dedicated Marketing sidebar');
assert.ok(!shell.includes("marketing:'tasks'"),'Marketing must not redirect to Follow-ups');
assert.ok(shell.includes("else if(page==='marketing')"),'Marketing needs its own route');
assert.ok(shell.includes("permission:action=>can('marketing',action)"),'Respect existing employee role permissions');
assert.ok(shell.includes("canLeads:can('leads','view'),canCustomers:can('customers','view')"),'New CRM-led Marketing may load only permitted leads and customers');
assert.ok(marketing.includes('ctx.companies.flatMap')===false,'Provider slots must be scoped to selected assigned companies');
assert.ok(marketing.includes('flatMap(c=>[1,2]'),'Support exactly two connection slots per company');
for(const term of ['overview','campaigns','contacts','templates','inbox','automations','reports','providers'])
 assert.ok(marketing.includes("'"+term+"'"),'Missing Marketing section '+term);
assert.ok(marketing.includes("consent_status==='opted_in'"),'Only opted-in contacts can qualify for campaigns');
assert.ok(marketing.includes("if(row.consent_source.trim().length<3)"),'Require evidence for opt-in');
assert.ok(marketing.includes("if(search.length<2)")===false,'Marketing global search is not the customer finder');
assert.ok(marketing.includes("setTimeout(()=>URL.revokeObjectURL"),'Download URLs must be revoked');
assert.ok(marketing.includes("if(!settings.admin&&!settings.permission?.('view'))"),'Require view permission');
assert.ok(sql.includes("grant select on public.%I to authenticated"),'RLS read-only grants');
assert.ok(sql.includes('enable row level security'),'Protect public Data API tables');
assert.ok(sql.includes("setup_state='not_configured' and enabled=false"),'Unverified integrations cannot be enabled from the browser');
assert.ok(sql.includes("provider_approval='not_verified'"),'Template approval cannot be forged by CRM users');
assert.ok(sql.includes("consent_status<>'opted_in'"),'Opt-in requires consent metadata');
assert.ok(!/fetch\s*\(\s*['"]https:\/\/whatsapp\.socialberries/i.test(marketing),'Do not guess provider APIs');
const globals={window:{},document:{},Intl,Array,Object,Map,Set,Date,Number,Error,String};
vm.runInNewContext(marketing,globals);
assert.equal(typeof globals.window.GreenRichWhatsAppMarketing.mount,'function');
assert.equal(typeof globals.window.GreenRichWhatsAppMarketing.send,'undefined','Do not claim unverified live sending');
assert.match(css,/\.grwa-tabs/);
console.log('PASS: Marketing menu, two providers per company, role-scoped CRM contacts, consent, campaign drafts, templates, automations, inbox, reporting and protected provider setup');
