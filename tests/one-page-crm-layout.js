'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const html=fs.readFileSync('secure.html','utf8');
const crm=fs.readFileSync('greenrich-crm-inline.css','utf8');
const attendance=fs.readFileSync('attendance-v3.css','utf8');
const tabs=['dashboard','sales','customers','leads','tasks','products','channels','reports'];
const template=html.match(/<template id="grCrmTemplate">([\s\S]*?)<\/template>/)?.[1]||'';
assert.match(template,/<nav id="navigation" class="gr-crm-tabs"/);
for(const name of tabs)assert.match(template,new RegExp('data-page="'+name+'"'));
assert.match(crm,/#grCrmWorkspace nav#navigation\.gr-crm-tabs\s*\{[\s\S]*?display:flex !important/);
assert.match(crm,/#grCrmWorkspace nav#navigation\.gr-crm-tabs\s*\{[\s\S]*?flex-wrap:wrap !important/);
assert.match(crm,/#grCrmWorkspace nav#navigation\.gr-crm-tabs > button\[data-page\]\s*\{[\s\S]*?flex:0 0 auto !important/);
assert.match(crm,/width:auto !important/);
assert.match(html,/#grCrmWorkspace nav#navigation\.gr-crm-tabs\{/,'Core compact nav style must be in secure.html, not solely in an external stylesheet');
assert.match(html,/#app \.main > header #attendanceQuick\{/,'Core switch-first header layout must ship in secure.html');
const topHeader=html.match(/<header>([\s\S]*?)<\/header>/)?.[1]||'';
assert.ok(topHeader.indexOf('id="attendanceQuick"')<topHeader.indexOf('class="profile"'),'Switch must be before profile');
assert.match(attendance,/#app header #attendanceQuick\s*\{[\s\S]*?margin-left:auto !important/);
assert.match(attendance,/#app header \.profile\s*\{[\s\S]*?text-align:right/);
assert.match(attendance,/#app header \.profile\s*\{[\s\S]*?order:3/);
console.log('PASS: compact horizontal CRM tabs and attendance switch before right-aligned user profile');
