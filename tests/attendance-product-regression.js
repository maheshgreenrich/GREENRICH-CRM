'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const inline=fs.readFileSync('greenrich-attendance-inline.js','utf8');
const html=fs.readFileSync('attendance-v3.html','utf8');
const portal=fs.readFileSync('greenrich-one.js','utf8');
new vm.Script(inline,{filename:'greenrich-attendance-inline.js'});
new vm.Script(portal,{filename:'greenrich-one.js'});
assert.match(portal,/GreenRichAttendance\.mount\(c\)/);
assert.doesNotMatch(portal,/location\.href='(?:attendance-control|attendance-v3|roles)\.html'/);
const required=['myCalendar','checkIn','checkOut','checkInTime','checkOutTime','myRows','correctionForm','leaveForm','bulkUsers','selectAllEmployees','pendingBadge','approvalPreview','adminChart','adminChartSummary','adminCorrections','adminLeaves','adminFilters'];
for(const id of required)assert.match(html,new RegExp('id="'+id+'"'),'Missing '+id);
const idMatches=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(idMatches.length,new Set(idMatches).size,'Duplicate attendance DOM ID');
assert.match(inline,/\/attendance\/check-in/);
assert.match(inline,/\/attendance\/check-out/);
assert.match(inline,/\/admin\/attendance\/bulk/);
assert.match(inline,/\/admin\/reports\/range/);
assert.match(inline,/\/admin\/staff/);
assert.match(inline,/data-bulk-status="HALF_DAY"/);
assert.match(inline,/await loadMine\(\)/);
assert.match(inline,/attendanceRights=/);
assert.match(inline,/\.av-employee-check:not\(:disabled\):checked/);
assert.equal([...inline.matchAll(/(?<!\$)\$\([^)]*\)\.(?:forEach|map|filter|find|some|reduce)\s*\(/g)].length,0);
console.log('PASS: One-page own attendance, calendar, bulk P/A/H, delegated roles, approvals and filtered exports');
