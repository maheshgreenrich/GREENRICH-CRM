'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const s=fs.readFileSync('greenrich-inventory.js','utf8'),html=fs.readFileSync('secure.html','utf8');
const window={};vm.runInNewContext(s,{window});
const ui=window.GreenRichInventory;
const page=ui.renderNewInventoryPage({companies:['grow-india'],companyName:()=> 'Greenrich'},'grow-india');
assert(page.indexOf('gr-inv-new-code')>0&&page.indexOf('gr-inv-new-code')<page.indexOf('gr-inv-new-tabs'));
assert.equal((page.match(/name="code"/g)||[]).length,1);
assert(page.includes('data-inv-create-stock-area'));
assert(page.includes('name="opening_stock"'));
assert(s.includes('track.onchange=syncStock'));
assert(s.includes('stockArea.hidden=!enabled'));
assert(s.includes("return toolbar+(m.track_inventory===false?'':stockSummary"));
const base={company_id:'grow-india',name:'Test',code:'TEST-FG01',stage:'FG',uom:'nos',source_type:'Make',saleable:true,track_inventory:true,opening_stock:'23'};
const make=ui.prepareInventoryRecord;
assert.equal(make(base,[],'id').payload.stock,23);
assert.equal(make({...base,track_inventory:false},[],'id').payload.stock,0);
assert.throws(()=>make({...base,opening_stock:'-5'},[],'id'),/Opening stock/);
assert.throws(()=>make({...base,stage:'RM',saleable:false,opening_stock:'5'},[],'id'),/approved warehouse/);
assert.match(html,/greenrich-inventory\.js\?v=20261123-independent-sku-material-type-v15/);
console.log('PASS SKU, conditional stock, opening count rules');
