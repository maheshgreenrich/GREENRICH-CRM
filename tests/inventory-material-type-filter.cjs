'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const source=fs.readFileSync('greenrich-inventory.js','utf8'),html=fs.readFileSync('secure.html','utf8');
const window={};vm.runInNewContext(source,{window});
const app=window.GreenRichInventory;
const original={id:'p1',original:'crm',company_id:'grow-india',code:'GRCM25',stage:'FG',name:'Composter',unit:'nos',material:{material_text:'001'}};
const edit=app.renderProductIdentifiers(original,true);
assert(edit.includes('data-inv-product-code')&&edit.includes('data-inv-material-type'));
assert(edit.includes('data-inv-material-text')&&edit.includes('data-inv-material-full'));
assert(edit.includes('value="GRCM25"')&&edit.includes('value="001"'));
assert(edit.includes('>FG001</output>'));
assert(!edit.includes('Code Suffix')&&!edit.includes('Result:'));
const alternate=app.renderProductIdentifiers({...original,stage:'SFG'},true);
assert(alternate.includes('value="GRCM25"')&&alternate.includes('>SFG001</output>'));
const form=app.renderNewInventoryPage({companies:['grow-india'],companyName:()=> 'Greenrich'},'grow-india');
assert(form.includes('data-inv-create-material-text')&&form.includes('data-inv-create-material-full'));
assert(form.includes('name="stage"')&&form.includes('name="code"'));
assert(!form.includes('name="material_suffix"'));
const record=app.prepareInventoryRecord({company_id:'grow-india',name:'Test',code:'OTHER-101',stage:'SFG',material_text:'001',uom:'nos',source_type:'Make',saleable:false,purchasable:false,track_inventory:true},[],'id1');
assert.equal(record.payload.code,'OTHER-101');
assert.equal(record.payload.material_type,'SFG');
assert.equal(record.payload.material_text,'001');
assert.equal(record.payload.material_full_text,'SFG001');
assert(source.includes(".rpc('gr_inventory_save_material_text'"));
assert(source.includes('p_expected_code:item.code,p_material_type:materialType,p_material_text:text'));
assert(source.includes("materialStage.addEventListener('change',updateMaterialPreview)"));
assert(source.includes("typeTextInput.addEventListener('input',updatePreview)"));
assert(source.includes("S.materialFilter==='all'||i.stage===S.materialFilter"));
assert.match(html,/greenrich-inventory[.]js[?]v=20261123-material-full-text-v16/);
console.log('PASS: Material Type + text produces full display, without changing SKU; filter retained.');
