'use strict';
/* GreenRich CRM Settings > Gmail integration, company-specific Google OAuth.
 * Client Secret is sent directly to the authenticated Edge Function and never
 * stored in browser localStorage or public GitHub source. */
(()=>{
 const esc=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
 const redirect='https://uawgwkplkvahhmhvroul.supabase.co/functions/v1/greenrich-quotation-gmail';
 async function mount(root,{db,companies,companyNames,notify}){
  let company=companies[0],busy=false;
  const call=async(body)=>{
   const {data,error}=await db.functions.invoke('greenrich-quotation-gmail',{body:{company_id:company,...body}});
   if(error||data?.error)throw Error(data?.error||error?.message||'Gmail backend is unavailable');
   return data;
  };
  const draw=async()=>{
   root.innerHTML='<div class="panel">Loading official Gmail connectivity settings…</div>';
   try{
    const data=await call({action:'status'});
    root.innerHTML='<div class="panel grgmail-settings"><h2>Gmail Connectivity & Settings</h2><p>Connect one official Gmail account per company. Credentials are configured here by Admin and sent directly to the secure backend.</p>'+
    '<label>Company<select id="grgmail-company">'+companies.map(c=>'<option value="'+esc(c)+'"'+(company===c?' selected':'')+'>'+esc(companyNames?.[c]||c)+'</option>').join('')+'</select></label>'+
    '<div class="grgmail-connection"><b>Connected account:</b> '+esc(data.connection?.sender_email||'Not connected')+'<br><b>Status:</b> '+esc(data.connection?.status||'disconnected')+'</div>'+
    (!data.configured?'<p class="grmail-alert">OAuth configuration incomplete. The Supabase encryption key must first be configured privately by an administrator.</p>':'')+
    '<form id="grgmail-credentials"><h3>Google OAuth Web Application</h3><label>Client ID<input name="client_id" autocomplete="off" maxlength="350" required placeholder="xxxx.apps.googleusercontent.com" value="'+esc(data.client_id||'')+'"></label>'+
    '<label>Client Secret<input type="password" name="client_secret" autocomplete="new-password" maxlength="800" required placeholder="Enter Google OAuth Client Secret"></label>'+
    '<p>For security, the existing Client Secret is never displayed. Saving new credentials will require Gmail reconnection.</p><button type="submit">Save OAuth credentials securely</button></form>'+
    '<div class="grgmail-setup"><h3>Google Cloud Setup</h3><p>Enable Gmail API and create an OAuth Web Application with this exact redirect URI:</p><div class="grgmail-uri"><code>'+esc(redirect)+'</code><button type="button" id="grgmail-copy">Copy</button></div>'+
    '<p><a href="https://console.cloud.google.com/auth/clients" target="_blank" rel="noopener noreferrer">Open Google OAuth Clients</a> · <a href="https://console.cloud.google.com/apis/library/gmail.googleapis.com" target="_blank" rel="noopener noreferrer">Enable Gmail API</a></p>'+
    '<p>One-time server secret: <code>GR_GMAIL_TOKEN_KEY_B64</code> (32 securely generated bytes, Base64). Set this only in <a target="_blank" rel="noopener noreferrer" href="https://supabase.com/dashboard/project/uawgwkplkvahhmhvroul/settings/functions">Supabase Edge Function Secrets</a>. Never enter encryption keys into a CRM page.</p></div>'+
    '<div class="grgmail-controls"><button type="button" id="grgmail-connect"'+(!data.configured?' disabled':'')+'>Connect / Reconnect Gmail</button><button type="button" id="grgmail-disconnect"'+(data.connection?.status!=='connected'?' disabled':'')+'>Disconnect Gmail</button></div></div>';
    root.querySelector('#grgmail-company').onchange=e=>{company=e.target.value;void draw()};
    root.querySelector('#grgmail-copy').onclick=()=>navigator.clipboard?.writeText(redirect).then(()=>notify?.('Redirect URI copied'));
    root.querySelector('#grgmail-credentials').onsubmit=async e=>{
     e.preventDefault();if(busy)return;
     const f=new FormData(e.target);busy=true;
     try{await call({action:'configure',client_id:f.get('client_id'),client_secret:f.get('client_secret')});notify?.('Company OAuth credentials saved securely. Connect Gmail to authorize.');await draw()}
     catch(error){notify?.(error.message,'error')}finally{busy=false}
    };
    root.querySelector('#grgmail-connect').onclick=async()=>{
     try{const response=await call({action:'connect'});window.location.assign(response.authorize_url)}catch(error){notify?.(error.message,'error')}
    };
    root.querySelector('#grgmail-disconnect').onclick=async()=>{
     if(!window.confirm('Disconnect the official company Gmail account?'))return;
     try{await call({action:'disconnect'});notify?.('Gmail disconnected');await draw()}catch(error){notify?.(error.message,'error')}
    };
   }catch(error){root.innerHTML='<div class="panel"><h2>Gmail Connectivity & Settings</h2><div class="notice">'+esc(error.message)+'</div></div>'}
  };
  await draw();
 }
 window.GreenRichGmailSettings={mount};
})();