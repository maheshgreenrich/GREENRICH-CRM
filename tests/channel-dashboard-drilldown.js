'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const js=fs.readFileSync('greenrich-crm-inline.js','utf8');
const html=fs.readFileSync('secure.html','utf8');
const css=fs.readFileSync('greenrich-crm-inline.css','utf8');
new vm.Script(js,{filename:'greenrich-crm-inline.js'});
const start=html.indexOf('<section id="dashboard"'),end=html.indexOf('</section><section id="sales"',start),dashboard=html.slice(start,end);
assert.ok(start>=0&&end>start,'Dashboard markup missing');
assert.ok(!dashboard.includes('Channel sales comparison'),'Redundant comparison section must be gone');
assert.ok(dashboard.includes('Sales insights'),'Sales insight card missing');
assert.ok(dashboard.includes('Order quantity'),'Order quantity heading missing in channel section');
assert.ok(html.includes('id="channel-orders-dialog"'),'Channel drilldown dialog missing');
for(const key of ['id="channel-orders-title"','id="channel-orders-subtitle"','id="channel-orders-details"','id="close-channel-orders"'])assert.ok(html.includes(key),key+' missing');
assert.ok(js.includes('const rows=filteredSales().filter(s=>channelForSale(s)===name)'),'Drilldown must apply all current filters');
assert.ok(js.includes('num(channelQuantity(name))')&&js.includes('channelOrderCount(name)'),'Channel rows must show units and orders');
assert.ok(js.includes("showChannelOrders(channel.dataset.channelDrill)"),'Legend must be clickable');
assert.ok(js.includes("onClick:(_event,elements)=>"),'Donut must be clickable');
assert.ok(js.includes('companyLabel(companyForSale(s))'),'Orders must display company');
assert.ok(js.includes('person?.address1'),'Orders must display customer address if present');
assert.ok(js.includes('invoiceNumber=s=>'),'Show invoice reference if present');
assert.ok(js.includes('Invoice document:'),'Do not imply absent invoice documents exist');
assert.ok(js.includes('Taxable:')&&js.includes('GST (')&&js.includes('Shipping:'),'Order details must show tax and shipping');
assert.ok(js.includes("['Average order value'")&&js.includes("['Repeat customers'")&&js.includes("['Pending orders'"));
assert.ok(js.includes('class="gr-product-revenue"'));
assert.ok(css.includes('font-size:13px!important'),'Compact product text size is required');
assert.ok(css.includes('white-space:nowrap!important'),'Avoid wrapping revenue');
for(const attendance of ['attendance-v3.css','attendance-v3.js','greenrich-attendance-inline.js'])assert.ok(!js.includes(attendance),'Attendance must stay unchanged');
console.log('PASS: compact top products, clickable channel quantities, orders, customers, available invoices and sales insights');
